#[test]
fn crashes_and_squeezes_use_the_same_canonical_features() {
    let mut up = crate::features::Features::default();
    let mut down = crate::features::Features::default();
    for p in [0.1, 0.7, 0.5, -0.4, 1.3, 2.0, 1.8, 0.3] {
        let x = up.next(p, 100);
        let z = down.next(-p, 100);
        let (a, sa) = crate::features::canonical(&x);
        let (b, sb) = crate::features::canonical(&z);
        assert_eq!(sa, -sb);
        for (a, b) in a.iter().zip(&b) { assert!((a-b).abs() < 1e-10); }
    }
}
