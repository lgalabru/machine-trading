//! Scoring v2's rules in plain words, for the agent's instruction.
//!
//! A task scored by v2 tells its agent how it is judged (GRADING_DECISIONS
//! D5): the three anchors, the loss weight, the near-breach charge, what a
//! breach costs (the per-session floor and the breach-rate penalty) and the
//! floor. The text is written from the grader's own
//! settings (`mtx_grader::scoring_v2`) and the flags the task's verifier
//! passes `mtx grade`, between two markers in its `instruction.md`, by
//! `mtx task sync`; `mtx task check` (and a test) fails when it is stale, so
//! the prompt can't drift from the code that grades.

use anyhow::{Context, Result, bail};
use mtx_grader::scoring_v2;

pub const BEGIN: &str = "<!-- mtx:scoring begin: generated by `mtx task sync` from scoring v2's settings and tests/test.sh -->";
pub const END: &str = "<!-- mtx:scoring end -->";
const BEGIN_PREFIX: &str = "<!-- mtx:scoring begin";

/// What the text depends on: the grader's defaults, or what the task's
/// verifier overrides.
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct Settings {
    /// `k`, `--loss-weight`.
    pub loss_weight: f64,
    /// `λ`, `--risk-weight`.
    pub risk_weight: f64,
    /// `φ`, `--anchor-floor`; `None` is the grader's default.
    pub anchor_floor: Option<f64>,
}

impl Default for Settings {
    fn default() -> Self {
        Self {
            loss_weight: scoring_v2::LOSS_WEIGHT,
            risk_weight: scoring_v2::RISK_WEIGHT,
            anchor_floor: None,
        }
    }
}

impl Settings {
    /// The settings a verifier script grades with: the grader's defaults,
    /// and any `--loss-weight`, `--risk-weight` or `--anchor-floor` it
    /// passes. Each at most once, as a plain number: a repeated flag or a
    /// task-scoped `TASK=VALUE` (which a grade of one task ignores) could
    /// make the text say other than what the grader does, so it is refused.
    pub fn of_verifier(script: &str) -> Result<Self> {
        let number = |flag: &str| -> Result<Option<f64>> {
            let values = flag_values(script, flag);
            if values.len() > 1 {
                bail!(
                    "tests/test.sh passes {flag} {} times: pass it once",
                    values.len()
                );
            }
            values
                .first()
                .map(|v| {
                    if v.contains('=') {
                        bail!(
                            "tests/test.sh: {flag} {v} is task-scoped; a task's verifier passes a plain value"
                        );
                    }
                    v.parse::<f64>()
                        .with_context(|| format!("tests/test.sh: {flag} {v} isn't a number"))
                })
                .transpose()
        };
        let defaults = Self::default();
        Ok(Self {
            loss_weight: number("--loss-weight")?.unwrap_or(defaults.loss_weight),
            risk_weight: number("--risk-weight")?.unwrap_or(defaults.risk_weight),
            anchor_floor: number("--anchor-floor")?,
        })
    }

    /// `φ` against a real informed bot.
    pub fn floor(&self) -> f64 {
        self.anchor_floor.unwrap_or(scoring_v2::ANCHOR_FLOOR)
    }
}

/// Every value a shell script passes `flag`, as `--flag value` or
/// `--flag=value`, unquoted, in order.
pub fn flag_values(script: &str, flag: &str) -> Vec<String> {
    let words: Vec<&str> = script
        .lines()
        .map(|l| l.split('#').next().unwrap_or(""))
        .flat_map(str::split_whitespace)
        .collect();
    let unquote = |v: &str| v.trim_matches(|c| c == '"' || c == '\'').to_string();
    let mut out = Vec::new();
    for (i, w) in words.iter().enumerate() {
        if *w == flag {
            out.extend(words.get(i + 1).map(|v| unquote(v)));
        } else if let Some(v) = w.strip_prefix(flag).and_then(|r| r.strip_prefix('=')) {
            out.push(unquote(v));
        }
    }
    out
}

/// The value a shell script passes `flag`: the last, as the grader's
/// argument parser takes it.
pub fn flag_value(script: &str, flag: &str) -> Option<String> {
    flag_values(script, flag).pop()
}

/// Whether a shell script passes `flag` at all.
pub fn has_flag(script: &str, flag: &str) -> bool {
    script
        .lines()
        .map(|l| l.split('#').next().unwrap_or(""))
        .flat_map(str::split_whitespace)
        .any(|w| w == flag || w.starts_with(&format!("{flag}=")))
}

/// A number as the text shows it: `1.5`, `0`, `−1`.
fn num(x: f64) -> String {
    let rounded = (x * 1e6).round() / 1e6;
    format!("{rounded}").replace('-', "−")
}

/// The scoring rules in plain words, markers included.
pub fn block(s: &Settings) -> String {
    let k = num(s.loss_weight);
    let sharpe = format!("{:.2}", scoring_v2::break_even_sharpe(s.loss_weight));
    let charge = num(s.risk_weight * s.loss_weight);
    let c = num(scoring_v2::BREACH_RATE_WEIGHT);
    let per_point = num(scoring_v2::breach_penalty(1, 100));
    let three_in_100 = num(scoring_v2::breach_penalty(3, 100));
    let floor = num(scoring_v2::RAW_FLOOR);
    let near_breach = if s.risk_weight > 0.0 {
        format!(
            "- **Running close to the loss limit costs.** The grader compares how deep your drawdowns go, as a share of the loss limit, with the informed bot's (the reference's when the informed bot's aren't known), and lets yours grow in proportion to how much more you earn than it. Drawdowns deeper than that give back part of your winnings: the charge grows with the square of the excess, and a bot that drew down to its limit in every session while the other never moved would pay {charge} times the loss limit a session. It only takes back winnings: it never makes a loss deeper, and a bot that takes no more risk than its edge justifies pays nothing.\n"
        )
    } else {
        String::new()
    };
    format!(
        "{BEGIN}\n\
         ### How the score works\n\
         \n\
         Your score puts your bot's PnL on a scale with three fixed points, measured on the same hidden sessions:\n\
         \n\
         - **0** is doing nothing.\n\
         - **0.5** is the task's reference bot, a sound and simple strategy.\n\
         - **1** is the task's informed bot. It knows everything the task's data could tell in principle (what kind of session it is, who trades on information, how fair value moves, what trading costs), but not how each session's randomness will play out, and it trades with your costs, limits and timing. 1 is reachable.\n\
         \n\
         The score is linear in PnL between those points, pooled over all the sessions: losing sessions count against winning ones. A bot that beats the informed bot scores above 1, and one that does worse than doing nothing scores below 0, down to {floor}. Your reward is the score clamped to between 0 and 1.\n\
         \n\
         - **Losses count {k} times.** Each session's loss is multiplied by {k} before the sessions are added up; gains count once. So a gamble with no edge scores no better than doing nothing, and neither does a strategy whose edge is small for its noise: with normally distributed session PnL, one whose per-session Sharpe ratio (mean session PnL over its standard deviation) is under about {sharpe}.\n\
         {near_breach}\
         - **A breach is a stop-out, and it costs the run.** Trading a market other than the task's, going over the position cap, drawing down past the loss limit, or ending a session liquidatable is a breach. A breached session counts at least as losing the whole loss limit, {k} times, and as its real loss counted {k} times when that is worse. If the task's risk desk closes your position at a limit, that stop-out is a breach too. On top of that, your score loses {c} times the share of sessions that breached: {per_point} for each 1% of sessions, the same for every breach, so 3 breaches in 100 sessions cost {three_in_100}.\n\
         - **Breaking the rules is worse than losing.** A call the RPC proxy refuses, tampering with the grade, or a bot that can't be graded scores {floor}, the bottom of the scale, whatever its sessions made.\n\
         {END}"
    )
}

/// `text` with the scoring block between its markers rewritten, or `None`
/// when it has no markers.
pub fn with_block(text: &str, s: &Settings) -> Result<Option<String>> {
    let Some(begin) = text.find(BEGIN_PREFIX) else {
        return Ok(None);
    };
    let end = text[begin..]
        .find(END)
        .map(|i| begin + i + END.len())
        .context("an `mtx:scoring begin` marker with no `mtx:scoring end` after it")?;
    Ok(Some(format!(
        "{}{}{}",
        &text[..begin],
        block(s),
        &text[end..]
    )))
}

/// Whether `text` carries the scoring block, as current as `s` writes it.
#[cfg(test)]
pub fn is_current(text: &str, s: &Settings) -> bool {
    matches!(with_block(text, s), Ok(Some(t)) if t == text)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_text_states_the_graders_own_numbers() {
        let text = block(&Settings::default());
        assert_eq!(scoring_v2::LOSS_WEIGHT, 1.5);
        assert!(text.contains("Losses count 1.5 times"), "{text}");
        assert!(text.contains("under about 0.16"), "{text}");
        assert!(text.contains("pay 1.5 times the loss limit a session"));
        assert_eq!(scoring_v2::BREACH_RATE_WEIGHT, 1.25);
        assert!(
            text.contains(
                "your score loses 1.25 times the share of sessions that breached: 0.0125 for each 1% of sessions, the same for every breach, so 3 breaches in 100 sessions cost 0.0375."
            ),
            "{text}"
        );
        assert!(!text.contains("caps the run"));
        assert!(text.contains("scores −1, the bottom of the scale"));
        assert!(text.starts_with(BEGIN) && text.ends_with(END));
        // Every number comes from the settings.
        let other = block(&Settings {
            loss_weight: 2.0,
            risk_weight: 0.5,
            anchor_floor: None,
        });
        assert!(other.contains("Losses count 2 times"));
        assert!(other.contains("under about 0.28"));
        assert!(other.contains("pay 1 times the loss limit"));
        let off = block(&Settings {
            risk_weight: 0.0,
            ..Settings::default()
        });
        assert!(!off.contains("Running close to the loss limit"));
    }

    #[test]
    fn the_settings_are_the_verifiers() {
        let script = "mtx grade \\\n  --scoring v2-headline \\\n  --loss-weight 2 \\\n  --risk-weight=\"0.5\" \\\n  --bot /app/bot\n# --anchor-floor 0.3\n";
        let s = Settings::of_verifier(script).unwrap();
        assert_eq!(
            (s.loss_weight, s.risk_weight, s.anchor_floor),
            (2.0, 0.5, None)
        );
        assert_eq!(s.floor(), scoring_v2::ANCHOR_FLOOR);
        assert_eq!(
            Settings::of_verifier("mtx grade").unwrap(),
            Settings::default()
        );
        assert!(Settings::of_verifier("--loss-weight much").is_err());
        // Repeated or task-scoped: refused, never guessed at.
        let twice = Settings::of_verifier("--risk-weight 0.5 --risk-weight 2").unwrap_err();
        assert!(twice.to_string().contains("2 times"), "{twice}");
        let scoped = Settings::of_verifier("--risk-weight t-spcx=0.5").unwrap_err();
        assert!(scoped.to_string().contains("task-scoped"), "{scoped}");
        assert_eq!(flag_value("--x 1 --x=2", "--x").as_deref(), Some("2"));
        assert!(has_flag(script, "--scoring") && !has_flag(script, "--anchor-floor"));
        assert_eq!(
            flag_value(script, "--scoring").as_deref(),
            Some("v2-headline")
        );
    }

    #[test]
    fn the_block_is_rewritten_in_place_and_a_stale_one_is_caught() {
        let s = Settings::default();
        let text =
            format!("# Task\n\n## Scoring\n\nIntro.\n\n{BEGIN}\nold rules\n{END}\n\n## Next\n");
        assert!(!is_current(&text, &s));
        let current = with_block(&text, &s).unwrap().unwrap();
        assert!(is_current(&current, &s));
        assert!(current.starts_with("# Task\n\n## Scoring\n\nIntro.\n\n"));
        assert!(current.ends_with(&format!("{END}\n\n## Next\n")));
        assert_eq!(with_block(&current, &s).unwrap().unwrap(), current);
        let k2 = Settings {
            loss_weight: 2.0,
            ..s
        };
        assert!(
            !is_current(&current, &k2),
            "a changed setting makes it stale"
        );
        // A prompt still stating the old run cap is stale.
        let new_rule = current
            .find("On top of that, your score loses")
            .expect("the breach-rate rule is stated");
        let end = new_rule + current[new_rule..].find('\n').unwrap();
        let capped = format!(
            "{}One breach in a run also caps the run's score at 0.5; two or more cap it at 0.{}",
            &current[..new_rule],
            &current[end..]
        );
        assert!(!is_current(&capped, &s));
        assert_eq!(with_block(&capped, &s).unwrap().unwrap(), current);
        assert_eq!(with_block("no markers", &s).unwrap(), None);
        assert!(!is_current("no markers", &s));
        assert!(with_block(&format!("{BEGIN}\nunterminated"), &s).is_err());
    }
}
