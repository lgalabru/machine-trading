//! The task folders as the one source of the lists the repository keeps
//! about them.
//!
//! Each `bench/tasks/<name>/task.toml` carries an `[metadata.mtx]` table; the
//! files below are written from those tables by `mtx task sync`, and
//! `mtx task check` (and a test) fails when one is stale:
//!
//! - `bench/tasks/tasks.just`, which the Justfile imports: the task-to-bot
//!   pairs, the reference bots, the ladders and the leak-audit needles;
//! - `bench/image/anchors.txt`, which the image build reads;
//! - `bench/tasks/dataset.toml`'s `[[tasks]]`;
//! - the task tables in `README.md` and `bench/tasks/README.md`, between
//!   their `mtx:tasks` markers.

use std::{
    collections::BTreeMap,
    path::{Path, PathBuf},
};

use anyhow::{Context, Result, bail};
use serde::Deserialize;

const GENERATED: &str = "Generated by `mtx task sync` from bench/tasks/*/task.toml; do not edit.";

/// A task folder's `task.toml`, as far as the lists need it.
#[derive(Debug, Clone)]
pub struct Task {
    /// The folder's name, the task's id.
    pub dir: String,
    /// Harbor's name for it, `solana-foundation/<dir>`.
    pub name: String,
    pub mtx: Mtx,
}

impl Mtx {
    pub fn anchor(&self) -> &str {
        self.anchor.as_deref().unwrap_or(&self.generator)
    }
}

/// `[metadata.mtx]`.
#[derive(Debug, Clone, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct Mtx {
    /// The scenario generator the task draws, by its name in the registry
    /// (`mtx_grader::generators`).
    pub generator: String,
    /// The reference bot: the crate directory `bots/<reference>`.
    pub reference: String,
    /// Where the image puts the reference for the verifier,
    /// `/opt/mtx/anchors/<anchor>`: the generator's name unless the task
    /// shares its generator with a task whose reference differs.
    pub anchor: Option<String>,
    /// The ladder's name: `bench/checks/ladder/<ladder>.json`, and the
    /// frozen exploit bots `bench/checks/exploits/<ladder>-*`.
    pub ladder: String,
    /// The emoji the root README's table opens the task's row with.
    pub emoji: String,
    /// The market, for the tasks README's table.
    pub market: String,
    /// What a good bot does, for the root README's table.
    pub summary: String,
    /// What a good bot does, for the tasks README's table.
    pub skill: String,
    /// Lines only the answers hold: the reference's source, the ladder's.
    /// `just leak-audit` fails if the agent's image holds one.
    #[serde(default)]
    pub leak_needles: Vec<String>,
}

#[derive(Deserialize)]
struct TaskToml {
    task: TaskTable,
    metadata: Metadata,
}

#[derive(Deserialize)]
struct TaskTable {
    name: String,
}

#[derive(Deserialize)]
struct Metadata {
    mtx: Option<Mtx>,
}

/// Every task under `bench/tasks`, by folder name.
pub fn load(root: &Path) -> Result<Vec<Task>> {
    let mut dirs: Vec<String> = std::fs::read_dir(root.join("bench/tasks"))
        .context("bench/tasks")?
        .flatten()
        .filter(|e| e.path().join("task.toml").is_file())
        .map(|e| e.file_name().to_string_lossy().to_string())
        .collect();
    dirs.sort();
    let tasks = dirs
        .into_iter()
        .map(|dir| {
            let path = root.join("bench/tasks").join(&dir).join("task.toml");
            let text = std::fs::read_to_string(&path)?;
            let parsed: TaskToml =
                toml::from_str(&text).with_context(|| path.display().to_string())?;
            let mtx = parsed
                .metadata
                .mtx
                .with_context(|| format!("{}: no [metadata.mtx] table", path.display()))?;
            if mtx_grader::generators::generator(&mtx.generator).is_none() {
                bail!(
                    "{}: no scenario generator `{}` (have: {})",
                    path.display(),
                    mtx.generator,
                    mtx_grader::generators::names().join(", ")
                );
            }
            for needle in &mtx.leak_needles {
                if needle.contains('|') || needle.contains('"') {
                    bail!(
                        "{}: a leak needle can't hold `|` or `\"`: {needle}",
                        path.display()
                    );
                }
            }
            if parsed.task.name != format!("solana-foundation/{dir}") {
                bail!(
                    "{}: task.name `{}` isn't solana-foundation/{dir}",
                    path.display(),
                    parsed.task.name
                );
            }
            Ok(Task {
                dir,
                name: parsed.task.name,
                mtx,
            })
        })
        .collect::<Result<Vec<_>>>()?;
    for task in &tasks {
        if let Some(other) = tasks
            .iter()
            .find(|o| o.mtx.anchor() == task.mtx.anchor() && o.mtx.reference != task.mtx.reference)
        {
            bail!(
                "{} and {} both anchor at /opt/mtx/anchors/{} with different references; set `anchor` in one's [metadata.mtx]",
                task.dir,
                other.dir,
                task.mtx.anchor()
            );
        }
    }
    Ok(tasks)
}

/// `items` without repeats, in order.
fn unique(items: impl Iterator<Item = String>) -> Vec<String> {
    let mut out: Vec<String> = Vec::new();
    for item in items {
        if !out.contains(&item) {
            out.push(item);
        }
    }
    out
}

/// The anchors, one per line, a shared one once.
fn anchors(tasks: &[Task]) -> String {
    let mut lines: Vec<String> = Vec::new();
    for t in tasks {
        let line = format!("{} {}", t.mtx.anchor(), t.mtx.reference);
        if !lines.contains(&line) {
            lines.push(line);
        }
    }
    lines.join("\n")
}

/// Every generated file: its path under the root and what it should hold,
/// given what it holds now.
fn render(root: &Path, tasks: &[Task]) -> Result<BTreeMap<PathBuf, String>> {
    let mut files = BTreeMap::new();
    let read = |path: &str| -> Result<String> {
        std::fs::read_to_string(root.join(path)).with_context(|| path.to_string())
    };

    let join = |f: &dyn Fn(&Task) -> String, sep: &str| -> String {
        tasks.iter().map(f).collect::<Vec<_>>().join(sep)
    };
    let needles = unique(
        tasks
            .iter()
            .flat_map(|t| t.mtx.leak_needles.iter().cloned()),
    )
    .join("|");
    files.insert(
        PathBuf::from("bench/tasks/tasks.just"),
        format!(
            "# {GENERATED}\n\
             # Each task and the bot its oracle runs, as `<task>=<bot>`.\n\
             references := \"{}\"\n\
             # The reference bots' crates, `bots/<bot>`.\n\
             reference_bots := \"{}\"\n\
             # Each task and its ladder, as `<task>=<ladder>`.\n\
             ladders := \"{}\"\n\
             # Lines only the answers hold, `|` apart.\n\
             leak_needles := \"{needles}\"\n",
            join(&|t| format!("{}={}", t.dir, t.mtx.reference), " "),
            unique(tasks.iter().map(|t| t.mtx.reference.clone())).join(" "),
            join(&|t| format!("{}={}", t.dir, t.mtx.ladder), " "),
        ),
    );

    files.insert(
        PathBuf::from("bench/image/anchors.txt"),
        format!(
            "# {GENERATED}\n# <scenario generator> <reference bot>, one per task.\n{}\n",
            anchors(tasks)
        ),
    );

    let dataset = read("bench/tasks/dataset.toml")?;
    files.insert(
        PathBuf::from("bench/tasks/dataset.toml"),
        dataset_with(&dataset, tasks)?,
    );

    let root_table = join(
        &|t| {
            format!(
                "| [{} `{}`](bench/tasks/{}) | {} |",
                t.mtx.emoji, t.dir, t.dir, t.mtx.summary
            )
        },
        "\n",
    );
    files.insert(
        PathBuf::from("README.md"),
        between_markers(
            &read("README.md")?,
            &format!("| Task | A good bot… |\n| --- | --- |\n{root_table}"),
        )?,
    );
    let tasks_table = join(
        &|t| {
            format!(
                "| [`{0}`]({0}) | {1} | {2} |",
                t.dir, t.mtx.market, t.mtx.skill
            )
        },
        "\n",
    );
    files.insert(
        PathBuf::from("bench/tasks/README.md"),
        between_markers(
            &read("bench/tasks/README.md")?,
            &format!("| Task | Market | A good bot… |\n| --- | --- | --- |\n{tasks_table}"),
        )?,
    );
    Ok(files)
}

const BEGIN: &str =
    "<!-- mtx:tasks begin: generated by `mtx task sync` from bench/tasks/*/task.toml -->";
const END: &str = "<!-- mtx:tasks end -->";

fn between_markers(text: &str, body: &str) -> Result<String> {
    let begin = text
        .find("<!-- mtx:tasks begin")
        .context("no `mtx:tasks begin` marker")?;
    let end = text.find(END).context("no `mtx:tasks end` marker")?;
    Ok(format!(
        "{}{BEGIN}\n{body}\n{}",
        &text[..begin],
        &text[end..]
    ))
}

/// The dataset manifest with its `[[tasks]]` listing every task: a task
/// already in it keeps its digest (`harbor sync` writes digests at release).
fn dataset_with(text: &str, tasks: &[Task]) -> Result<String> {
    #[derive(Deserialize)]
    struct Dataset {
        #[serde(default)]
        tasks: Vec<Entry>,
    }
    #[derive(Deserialize)]
    struct Entry {
        name: String,
        digest: Option<String>,
    }
    let parsed: Dataset = toml::from_str(text).context("dataset.toml")?;
    let digests: BTreeMap<_, _> = parsed
        .tasks
        .into_iter()
        .map(|e| (e.name, e.digest))
        .collect();
    let head = match text.find("[[tasks]]") {
        Some(i) => &text[..i],
        None => text,
    };
    let mut out = head.trim_end().to_string();
    out.push('\n');
    for task in tasks {
        out.push_str(&format!("\n[[tasks]]\nname = \"{}\"\n", task.name));
        if let Some(Some(digest)) = digests.get(&task.name) {
            out.push_str(&format!("digest = \"{digest}\"\n"));
        }
    }
    Ok(out)
}

/// Write every generated file. Returns the ones that changed.
pub fn sync(root: &Path) -> Result<Vec<PathBuf>> {
    let mut changed = Vec::new();
    for (path, content) in render(root, &load(root)?)? {
        let full = root.join(&path);
        if std::fs::read_to_string(&full).ok().as_deref() != Some(&content) {
            std::fs::write(&full, content).with_context(|| path.display().to_string())?;
            changed.push(path);
        }
    }
    Ok(changed)
}

/// The generated files that are stale.
pub fn stale(root: &Path) -> Result<Vec<PathBuf>> {
    Ok(render(root, &load(root)?)?
        .into_iter()
        .filter(|(path, content)| {
            std::fs::read_to_string(root.join(path)).ok().as_deref() != Some(content.as_str())
        })
        .map(|(path, _)| path)
        .collect())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_generated_lists_are_current() {
        let root = crate::authoring::repo_root();
        let stale = stale(&root).unwrap();
        assert!(stale.is_empty(), "run `mtx task sync`: stale {stale:?}");
    }

    #[test]
    fn every_task_is_listed() {
        let tasks = load(&crate::authoring::repo_root()).unwrap();
        assert!(tasks.len() >= 4);
        for task in &tasks {
            assert!(
                task.mtx.leak_needles.iter().all(|n| !n.is_empty()),
                "{}",
                task.dir
            );
        }
    }

    #[test]
    fn a_shared_generator_needs_its_own_anchor() {
        let dir = std::env::temp_dir().join(format!("mtx-tasks-{}", uuid::Uuid::new_v4().simple()));
        let real = crate::authoring::repo_root();
        for task in ["flash-crash-spcx", "market-making-spcx"] {
            std::fs::create_dir_all(dir.join("bench/tasks").join(task)).unwrap();
            let toml =
                std::fs::read_to_string(real.join("bench/tasks").join(task).join("task.toml"))
                    .unwrap();
            // Both tasks draw flash-crash, with different references.
            let toml = toml.replace(
                "generator = \"market-making\"",
                "generator = \"flash-crash\"",
            );
            std::fs::write(dir.join("bench/tasks").join(task).join("task.toml"), toml).unwrap();
        }
        let err = load(&dir).unwrap_err().to_string();
        assert!(err.contains("both anchor"), "{err}");
        std::fs::remove_dir_all(&dir).unwrap();
    }

    #[test]
    fn markers_are_replaced_in_place() {
        let text = format!("a\n{BEGIN}\nold\n{END}\nb\n");
        let out = between_markers(&text, "new").unwrap();
        assert_eq!(out, format!("a\n{BEGIN}\nnew\n{END}\nb\n"));
        assert_eq!(between_markers(&out, "new").unwrap(), out);
        assert!(between_markers("none", "x").is_err());
    }

    #[test]
    fn a_dataset_keeps_digests_and_gains_tasks() {
        let task = |dir: &str| Task {
            dir: dir.into(),
            name: format!("solana-foundation/{dir}"),
            mtx: Mtx {
                generator: "flash-crash".into(),
                reference: "reference".into(),
                anchor: None,
                ladder: "flash-crash".into(),
                emoji: String::new(),
                market: String::new(),
                summary: String::new(),
                skill: String::new(),
                leak_needles: vec![],
            },
        };
        let text = "[dataset]\nname = \"x/y\"\n\n[[tasks]]\nname = \"solana-foundation/a\"\ndigest = \"sha256:1\"\n\n[[tasks]]\nname = \"solana-foundation/gone\"\ndigest = \"sha256:2\"\n";
        let out = dataset_with(text, &[task("a"), task("b")]).unwrap();
        assert_eq!(
            out,
            "[dataset]\nname = \"x/y\"\n\n[[tasks]]\nname = \"solana-foundation/a\"\ndigest = \"sha256:1\"\n\n[[tasks]]\nname = \"solana-foundation/b\"\n"
        );
    }
}
