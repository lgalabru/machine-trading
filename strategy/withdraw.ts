import { loadOrCreate, phoenix, rpc, send } from "./lib.ts";
import { address } from "@solana/kit";
await phoenix.exchange.ready();
const s = await loadOrCreate("strategy");
const m: any = (await phoenix.rpc.hawkeye.viewMargin({ authority: s.address } as any)).returnData.decoded;
const amt = BigInt(m.withdrawableCollateralQuoteLots);
const w = await phoenix.ixs.buildWithdrawIxs({ authority: s.address as any, amount: amt });
await send(s, w.instructions as any, `withdraw ${Number(amt) / 1e6} USDC`);
await new Promise((r) => setTimeout(r, 1000));
const bal = await rpc.getTokenAccountBalance(address("DCxBCsErpWAPTk7oNAkHafjBTLZEz6sqS7idC8HoiUJ2")).send();
console.log("strategy wallet USDC:", bal.value.uiAmountString);
